//! Generates `src/commands/table.rs` from a live server's `COMMAND INFO` and
//! `COMMAND DOCS`. Only reads from the server. Run it through
//! `scripts/gen-commands.sh`, which picks the server and writes the file:
//!
//!     cargo run -p redcrab-core --example gen_commands -- redis://127.0.0.1:6379 > table.rs
//!
//! The flags are what each command declares about itself. Some declare
//! `readonly` and still change data (PFCOUNT, whose `may_replicate` flag
//! `COMMAND INFO` hides; module commands such as CF.COMPACT), so the
//! read-only gate overrides them in `WRITE_EXTRA` / `ADMIN_EXTRA` in
//! `src/commands/mod.rs`. After regenerating against a newer server or new
//! modules, review the new `readonly` module commands there.

use std::{
    collections::{BTreeMap, BTreeSet, HashMap},
    fmt::Write as _,
};

use anyhow::{Context as _, Result, bail};
use redcrab_core::commands::{AclCategories, Flags};
use redis::Value;

fn main() -> Result<()> {
    let url = std::env::args()
        .nth(1)
        .unwrap_or_else(|| "redis://127.0.0.1:6379".into());
    let mut con = redis::Client::open(url.as_str())?
        .get_connection()
        .with_context(|| format!("could not connect to {url}"))?;
    let info: Value = redis::cmd("COMMAND").arg("INFO").query(&mut con)?;
    let docs: Value = redis::cmd("COMMAND").arg("DOCS").query(&mut con)?;
    let server: String = redis::cmd("INFO").arg("server").query(&mut con)?;
    let modules: Value = redis::cmd("MODULE").arg("LIST").query(&mut con)?;

    let version = server
        .lines()
        .find_map(|line| line.strip_prefix("redis_version:"))
        .unwrap_or("unknown")
        .trim()
        .to_string();
    let modules: Vec<String> = items(&modules)
        .iter()
        .map(|module| {
            let fields = map(module);
            let field = |name: &str| {
                fields
                    .iter()
                    .find(|(key, _)| key == name)
                    .map_or_else(String::new, |(_, value)| text(value))
            };
            format!("{} {}", field("name"), field("ver"))
        })
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect();

    let mut docs_by_name = HashMap::new();
    index_docs(&docs, &mut docs_by_name);

    let mut entries = BTreeMap::new();
    let mut unknown = BTreeSet::new();
    for command in items(&info) {
        collect(command, &[], &docs_by_name, &mut entries, &mut unknown)?;
    }
    if !unknown.is_empty() {
        bail!(
            "unknown flags or ACL categories: {}; add them to Flags / AclCategories in src/commands/mod.rs",
            unknown.into_iter().collect::<Vec<_>>().join(", ")
        );
    }

    let mut out = String::new();
    let modules = if modules.is_empty() {
        String::new()
    } else {
        format!(" with modules {}", modules.join(", "))
    };
    writeln!(
        out,
        "// @generated by scripts/gen-commands.sh from Redis {version}{modules}."
    )?;
    writeln!(
        out,
        "// Do not edit by hand; regenerate with `scripts/gen-commands.sh [redis://host:port]`."
    )?;
    writeln!(out)?;
    writeln!(out, "use super::{{AclCategories, CommandSpec, Flags}};")?;
    writeln!(out)?;
    writeln!(out, "#[rustfmt::skip]")?;
    writeln!(out, "pub(super) static COMMANDS: &[CommandSpec] = &[")?;
    for line in entries.values() {
        writeln!(out, "    {line}")?;
    }
    writeln!(out, "];")?;
    print!("{out}");
    eprintln!("{} commands and subcommands", entries.len());
    Ok(())
}

/// Indexes `COMMAND DOCS` by lower-case `container|sub` name, the way
/// `COMMAND INFO` names commands.
fn index_docs<'a>(docs: &'a Value, out: &mut HashMap<String, &'a Value>) {
    for (name, doc) in map(docs) {
        if let Some((_, subs)) = map(doc).into_iter().find(|(key, _)| key == "subcommands") {
            index_docs(subs, out);
        }
        out.insert(name.to_ascii_lowercase(), doc);
    }
}

/// Renders the table line of one `COMMAND INFO` entry and of its subcommands.
/// `inherited` are the container's ACL categories: module subcommands often
/// declare none (`FT.CONFIG SET`), and an empty set would make an admin
/// command look harmless.
fn collect(
    command: &Value,
    inherited: &[String],
    docs: &HashMap<String, &Value>,
    entries: &mut BTreeMap<String, String>,
    unknown: &mut BTreeSet<String>,
) -> Result<()> {
    let fields = items(command);
    let [name, arity, flags, _, _, _, categories, ..] = fields else {
        bail!("unexpected COMMAND INFO entry: {command:?}");
    };
    let id = text(name).to_ascii_lowercase();
    let name = id.replace('|', " ").to_ascii_uppercase();
    let arity = int(arity);
    let doc: Vec<(String, &Value)> = docs.get(&id).map(|doc| map(doc)).unwrap_or_default();
    let field = |key: &str| doc.iter().find(|(k, _)| k == key).map(|(_, v)| *v);
    let field_text = |key: &str| field(key).map(text).unwrap_or_default();

    let mut flag_names: Vec<String> = items(flags).iter().map(text).collect();
    flag_names.extend(
        field("doc_flags")
            .map(items)
            .unwrap_or_default()
            .iter()
            .map(text),
    );
    let flags = idents(
        &flag_names,
        |name| Flags::from_name(name).is_some(),
        unknown,
    );
    let mut category_names: Vec<String> = items(categories)
        .iter()
        .map(|c| text(c).trim_start_matches('@').to_string())
        .collect();
    if category_names.is_empty() {
        category_names = inherited.to_vec();
    }
    let categories = idents(
        &category_names,
        |name| AclCategories::from_name(name).is_some(),
        unknown,
    );

    let subcommands = fields.get(9).map(items).unwrap_or_default();
    let group = match field_text("group").as_str() {
        "module" => module_group(&field_text("module")),
        group => group.to_string(),
    };
    let syntax = match field("arguments") {
        _ if !subcommands.is_empty() => format!("{name} <subcommand>"),
        Some(arguments) => {
            let arguments: Vec<String> = items(arguments).iter().map(argument).collect();
            format!("{name} {}", arguments.join(" "))
                .trim_end()
                .to_string()
        }
        // No argument docs (some module commands): hint that it takes some.
        None => {
            let words = name.split(' ').count() as i64;
            if arity > words || arity < -words {
                format!("{name} ...")
            } else {
                name.clone()
            }
        }
    };
    let line = format!(
        "CommandSpec {{ name: {name:?}, arity: {arity}, flags: flags!({flags}), acl: acl!({categories}), group: {group:?}, since: {since:?}, summary: {summary:?}, syntax: {syntax:?} }},",
        since = field_text("since"),
        summary = one_line(&field_text("summary")),
    );
    if entries.insert(name.clone(), line).is_some() {
        bail!("{name} is listed twice");
    }
    for sub in subcommands {
        collect(sub, &category_names, docs, entries, unknown)?;
    }
    Ok(())
}

/// `WRITE | DENYOOM` for the `flags!` and `acl!` macros; names the crate does
/// not know yet are collected into `unknown`.
fn idents(
    names: &[String],
    known: impl Fn(&str) -> bool,
    unknown: &mut BTreeSet<String>,
) -> String {
    let mut out = Vec::new();
    for name in names {
        if known(name) {
            out.push(name.to_ascii_uppercase());
        } else {
            unknown.insert(name.clone());
        }
    }
    out.join(" | ")
}

/// A short group name for a module's commands.
fn module_group(module: &str) -> String {
    match module.to_ascii_lowercase().as_str() {
        "rejson" => "json".into(),
        "bf" => "bloom".into(),
        other => other.into(),
    }
}

/// One argument in the notation of the Redis docs: `[NX | XX]`,
/// `<LEFT | RIGHT>`, `key [key ...]`, `[LIMIT offset count]`.
fn argument(arg: &Value) -> String {
    let fields = map(arg);
    let field = |key: &str| fields.iter().find(|(k, _)| k == key).map(|(_, v)| *v);
    let field_text = |key: &str| field(key).map(text);
    let flags: Vec<String> = field("flags")
        .map(items)
        .unwrap_or_default()
        .iter()
        .map(text)
        .collect();
    let has = |flag: &str| flags.iter().any(|f| f == flag);
    let (optional, multiple, multiple_token) =
        (has("optional"), has("multiple"), has("multiple_token"));
    // MIGRATE takes an empty string in place of a key.
    let token = field_text("token").map(|t| if t.is_empty() { r#""""#.to_string() } else { t });
    let kind = field_text("type").unwrap_or_default();
    let children = || -> Vec<String> {
        field("arguments")
            .map(items)
            .unwrap_or_default()
            .iter()
            .map(argument)
            .collect()
    };

    let core = match kind.as_str() {
        "pure-token" => token
            .clone()
            .unwrap_or_else(|| field_text("name").unwrap_or_default().to_uppercase()),
        "oneof" => {
            let choices = children().join(" | ");
            // An optional choice without a token is already in brackets.
            if optional && token.is_none() && !multiple {
                choices
            } else {
                format!("<{choices}>")
            }
        }
        "block" => children().join(" "),
        _ => field_text("display_text")
            .or_else(|| field_text("name"))
            .unwrap_or_default(),
    };
    let token = token.filter(|_| kind != "pure-token");
    let with_token = |s: &str| match &token {
        Some(token) => format!("{token} {s}"),
        None => s.to_string(),
    };
    let one = if !multiple {
        with_token(&core)
    } else if multiple_token {
        let one = with_token(&core);
        format!("{one} [{one} ...]")
    } else {
        with_token(&format!("{core} [{core} ...]"))
    };
    if optional { format!("[{one}]") } else { one }
}

fn one_line(s: &str) -> String {
    s.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn items(v: &Value) -> &[Value] {
    match v {
        Value::Array(items) | Value::Set(items) => items,
        _ => &[],
    }
}

/// A RESP3 map, or the flat key/value array RESP2 sends instead.
fn map(v: &Value) -> Vec<(String, &Value)> {
    match v {
        Value::Map(pairs) => pairs.iter().map(|(k, v)| (text(k), v)).collect(),
        Value::Array(items) => items
            .as_chunks::<2>()
            .0
            .iter()
            .map(|[k, v]| (text(k), v))
            .collect(),
        _ => Vec::new(),
    }
}

fn text(v: &Value) -> String {
    match v {
        Value::BulkString(bytes) => String::from_utf8_lossy(bytes).into_owned(),
        Value::SimpleString(s) => s.clone(),
        Value::VerbatimString { text, .. } => text.clone(),
        Value::Okay => "OK".into(),
        Value::Int(i) => i.to_string(),
        _ => String::new(),
    }
}

fn int(v: &Value) -> i64 {
    match v {
        Value::Int(i) => *i,
        other => text(other).parse().unwrap_or(0),
    }
}
